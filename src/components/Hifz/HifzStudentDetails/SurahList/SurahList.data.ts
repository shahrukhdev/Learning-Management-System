export const getJuzLabel = (surahNumber: number): string => {
    const juz = SURAH_JUZ_RANGES[surahNumber];

    if (!juz) {
        return "-";
    }

    if (juz.start === juz.end) {
        return `${juz.start}`;
    }

    return `${juz.start}-${juz.end}`;
};